from __future__ import annotations

import json
import struct
from dataclasses import dataclass
from pathlib import Path

# NextOS labeled flat binary (NXFL).
# Packager reads the label table and places each payload blob at `address`.
MAGIC = b"NXFL"
VERSION = 1


@dataclass(frozen=True, slots=True)
class FlatLabel:
    name: str
    address: int
    offset: int
    size: int


@dataclass(frozen=True, slots=True)
class FlatImage:
    labels: list[FlatLabel]
    payload: bytes

    def label_map(self) -> dict[str, FlatLabel]:
        return {label.name: label for label in self.labels}


def generate_section_script(layout: dict[str, int], *, entry: str | None = None) -> str:
    """Linker script that keeps layout slots as named ELF sections.

    Absolute VMAs match SetExecutableLayout so inter-section relocations resolve
    correctly. The ELF itself is only an intermediate — nextbuild extracts each
    section into the labeled flat image.
    """
    if not layout:
        raise ValueError("executable layout is empty")

    ordered = sorted(layout.items(), key=lambda item: item[1])
    entry_symbol = entry or ordered[0][0]
    lines = [
        "/* Generated by nextbuild — intermediate only */",
        "OUTPUT_FORMAT(\"elf64-x86-64\")",
        f"ENTRY({entry_symbol})",
        "SECTIONS",
        "{",
    ]
    for name, address in ordered:
        lines.append(f"  .{name} 0x{address:X} : {{")
        lines.append(f"    KEEP(*(.{name}))")
        lines.append(f"    KEEP(*(.text.{name}))")
        lines.append(f"    *(.text.{name}.*)")
        lines.append("  }")
        lines.append("")

    lines.extend(
        [
            "  .text : { *(.text .text.*) }",
            "  .rodata : { *(.rodata .rodata.*) }",
            "  .data : { *(.data .data.*) }",
            "  .bss : { *(.bss .bss.*) *(COMMON) }",
            "}",
            "",
        ]
    )
    return "\n".join(lines)


def write_section_script(path: Path, layout: dict[str, int], *, entry: str | None = None) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(generate_section_script(layout, entry=entry), encoding="utf-8")
    return path


def pack_labeled_flat(segments: list[tuple[str, int, bytes]]) -> FlatImage:
    """Pack (name, address, blob) segments into an NXFL image."""
    payload = bytearray()
    labels: list[FlatLabel] = []
    for name, address, blob in segments:
        offset = len(payload)
        payload.extend(blob)
        labels.append(FlatLabel(name=name, address=address, offset=offset, size=len(blob)))
    return FlatImage(labels=labels, payload=bytes(payload))


def serialize_nxfl(image: FlatImage) -> bytes:
    """Binary layout:
    magic[4] version:u32 label_count:u32 payload_offset:u32
    repeated labels:
      name_len:u16 name[name_len] address:u64 file_offset:u64 size:u64
    payload bytes
    """
    table = bytearray()
    for label in image.labels:
        name = label.name.encode("utf-8")
        if len(name) > 0xFFFF:
            raise ValueError(f"label name too long: {label.name!r}")
        table.extend(struct.pack("<H", len(name)))
        table.extend(name)
        table.extend(struct.pack("<QQQ", label.address, label.offset, label.size))

    header_size = 16
    payload_offset = header_size + len(table)
    # file_offset stored in labels is relative to payload start; rewrite absolute file offsets
    adjusted_table = bytearray()
    for label in image.labels:
        name = label.name.encode("utf-8")
        adjusted_table.extend(struct.pack("<H", len(name)))
        adjusted_table.extend(name)
        adjusted_table.extend(
            struct.pack("<QQQ", label.address, payload_offset + label.offset, label.size)
        )

    header = struct.pack("<4sIII", MAGIC, VERSION, len(image.labels), payload_offset)
    return header + adjusted_table + image.payload


def write_nxfl(path: Path, image: FlatImage) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(serialize_nxfl(image))
    return path


def write_labels_sidecar(path: Path, image: FlatImage, *, layout: dict[str, int]) -> Path:
    """Human/machine readable map for the image packager."""
    path.parent.mkdir(parents=True, exist_ok=True)
    data = {
        "format": "NXFL",
        "version": VERSION,
        "layout": {name: f"0x{addr:X}" for name, addr in layout.items()},
        "labels": [
            {
                "name": label.name,
                "address": f"0x{label.address:X}",
                "address_int": label.address,
                "payload_offset": label.offset,
                "size": label.size,
            }
            for label in image.labels
        ],
    }
    path.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")
    return path


def parse_nxfl(data: bytes) -> FlatImage:
    if len(data) < 16 or data[:4] != MAGIC:
        raise ValueError("not an NXFL image")
    _magic, version, count, payload_offset = struct.unpack_from("<4sIII", data, 0)
    if version != VERSION:
        raise ValueError(f"unsupported NXFL version: {version}")
    pos = 16
    labels: list[FlatLabel] = []
    for _ in range(count):
        (name_len,) = struct.unpack_from("<H", data, pos)
        pos += 2
        name = data[pos : pos + name_len].decode("utf-8")
        pos += name_len
        address, file_offset, size = struct.unpack_from("<QQQ", data, pos)
        pos += 24
        labels.append(
            FlatLabel(
                name=name,
                address=address,
                offset=file_offset - payload_offset,
                size=size,
            )
        )
    payload = data[payload_offset:]
    return FlatImage(labels=labels, payload=payload)
